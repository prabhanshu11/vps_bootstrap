#!/bin/bash
# setup-wireguard.sh — the wg-vdi hub: a self-hosted WireGuard relay so the laptop's
# Moonlight reaches the desktop's Sunshine from anywhere (no third-party coordination
# server; Tailscale stays as the separate fallback on the peers).
#
#   10.77.0.0/24   VPS .1 (this host, UDP 51820), desktop .2, laptop .3
#
# Run by .github/workflows/wireguard.yml with the private key on stdin (secret
# WG_VDI_VPS_KEY). Idempotent. Only peers in wireguard/peers.conf can join; Sunshine is
# never exposed publicly — the VPS only forwards wg-vdi <-> wg-vdi.
set -euo pipefail
DIR="$(cd "$(dirname "$0")/.." && pwd)"
IF=wg-vdi; PORT=51820
log() { echo "[$(date +'%Y-%m-%d %H:%M:%S')] wireguard: $*"; }
[[ $EUID -eq 0 ]] || { echo "must run as root" >&2; exit 1; }

command -v wg >/dev/null || { log "installing wireguard-tools"; apt-get update -qq; apt-get install -y -qq wireguard-tools; }
install -d -m 700 /etc/wireguard

key=""
[[ -t 0 ]] || key="$(cat | tr -d '[:space:]')"
if [[ -n "$key" ]]; then
    umask 077; printf '%s\n' "$key" > /etc/wireguard/vps.key
fi
[[ -s /etc/wireguard/vps.key ]] || { echo "no private key (stdin empty, /etc/wireguard/vps.key missing)" >&2; exit 1; }
pub="$(wg pubkey < /etc/wireguard/vps.key)"
want="$(tr -d '[:space:]' < "$DIR/wireguard/vps.pub")"
[[ "$pub" == "$want" ]] || { echo "VPS key does not match wireguard/vps.pub ($pub)" >&2; exit 1; }

tmp="$(mktemp)"; umask 077
{
    echo "# Generated by vps_bootstrap/scripts/setup-wireguard.sh — do not edit by hand"
    echo "[Interface]"
    echo "Address = 10.77.0.1/24"
    echo "ListenPort = $PORT"
    echo "PrivateKey = $(cat /etc/wireguard/vps.key)"
    while read -r name pk ip; do
        [[ -z "$name" || "$name" == \#* ]] && continue
        echo; echo "# $name"; echo "[Peer]"; echo "PublicKey = $pk"; echo "AllowedIPs = $ip/32"
    done < "$DIR/wireguard/peers.conf"
} > "$tmp"
if ! cmp -s "$tmp" /etc/wireguard/$IF.conf; then
    install -m 600 "$tmp" /etc/wireguard/$IF.conf; changed=1; log "config updated"
fi
rm -f "$tmp"

echo "net.ipv4.ip_forward = 1" > /etc/sysctl.d/99-wg-vdi.conf
sysctl -q -p /etc/sysctl.d/99-wg-vdi.conf

if command -v ufw >/dev/null; then
    ufw allow $PORT/udp comment 'wg-vdi relay' >/dev/null
    ufw route allow in on $IF out on $IF comment 'wg-vdi peer to peer' >/dev/null
fi

systemctl enable -q wg-quick@$IF
if systemctl is-active -q wg-quick@$IF; then
    [[ -n "${changed:-}" ]] && wg syncconf $IF <(wg-quick strip $IF)
else
    systemctl start wg-quick@$IF
fi
log "up: $(wg show $IF | grep -c '^peer') peer(s), public key $pub"
wg show $IF latest-handshakes || true
